-- Flexi Support Helpdesk: Firebase Authentication + Supabase Postgres database.
-- Project: ryvauylmymcvbvvlaceb
-- Existing public.profiles and all unrelated tables are left untouched.
-- For an existing installation, this migration converts support identity columns
-- from Supabase Auth UUIDs to Firebase UID text and rebuilds only support RLS.

create extension if not exists pgcrypto;
create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table if not exists public.support_staff (
  user_id text primary key,
  email text not null,
  display_name text not null default 'Flexi Support',
  role text not null default 'agent' check (role in ('agent','admin')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  user_id text not null,
  requester_email text not null,
  subject text not null check (char_length(trim(subject)) between 4 and 160),
  description text not null check (char_length(trim(description)) between 10 and 8000),
  category text not null default 'General' check (category in ('General','Account & Login','Payments','JAMB/WAEC CBT','Website Problem','Learning Support','Bug Report','Other')),
  priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
  status text not null default 'open' check (status in ('open','in_progress','waiting_customer','resolved','closed')),
  assigned_to text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_message_at timestamptz not null default now()
);

create table if not exists public.support_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.support_tickets(id) on delete cascade,
  sender_id text not null,
  body text not null check (char_length(trim(body)) between 1 and 10000),
  is_internal boolean not null default false,
  created_at timestamptz not null default now()
);

do $$
declare p record;
begin
  for p in select schemaname, tablename, policyname from pg_policies
    where schemaname='public' and tablename in ('support_staff','support_tickets','support_messages')
  loop
    execute format('drop policy if exists %I on %I.%I',p.policyname,p.schemaname,p.tablename);
  end loop;
end $$;

-- Remove only the old support-table foreign keys to auth.users before changing
-- the identity columns to Firebase UID text. Ticket/message records are preserved.
do $$
declare c record;
begin
  for c in
    select conrelid::regclass as tbl, conname
    from pg_constraint
    where contype='f'
      and conrelid in ('public.support_staff'::regclass,'public.support_tickets'::regclass,'public.support_messages'::regclass)
  loop
    execute format('alter table %s drop constraint %I', c.tbl, c.conname);
  end loop;
end $$;

alter table public.support_staff alter column user_id type text using user_id::text;
alter table public.support_tickets alter column user_id type text using user_id::text;
alter table public.support_tickets alter column assigned_to type text using assigned_to::text;
alter table public.support_messages alter column sender_id type text using sender_id::text;
alter table public.support_tickets alter column user_id set not null;
alter table public.support_messages alter column sender_id set not null;

alter table public.support_tickets drop constraint if exists support_tickets_assigned_to_fkey;
alter table public.support_tickets
  add constraint support_tickets_assigned_to_fkey
  foreign key (assigned_to) references public.support_staff(user_id) on delete set null;

create index if not exists support_tickets_user_updated_idx on public.support_tickets (user_id, last_message_at desc);
create index if not exists support_tickets_status_updated_idx on public.support_tickets (status, last_message_at desc);
create index if not exists support_messages_ticket_created_idx on public.support_messages (ticket_id, created_at asc);

create or replace function private.support_firebase_uid()
returns text language sql stable security definer set search_path = ''
as $$ select auth.jwt() ->> 'sub' $$;

create or replace function private.support_is_staff()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.support_staff s
    where s.user_id = (select private.support_firebase_uid()) and s.active = true
  );
$$;

revoke all on function private.support_firebase_uid() from public, anon;
revoke all on function private.support_is_staff() from public, anon;
grant execute on function private.support_firebase_uid() to authenticated;
grant execute on function private.support_is_staff() to authenticated;

create or replace function public.support_touch_ticket()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  update public.support_tickets set last_message_at = new.created_at, updated_at = now() where id = new.ticket_id;
  return new;
end;
$$;
revoke all on function public.support_touch_ticket() from public, anon, authenticated;
drop trigger if exists support_message_touch_ticket on public.support_messages;
create trigger support_message_touch_ticket after insert on public.support_messages
for each row execute function public.support_touch_ticket();

alter table public.support_staff enable row level security;
alter table public.support_tickets enable row level security;
alter table public.support_messages enable row level security;


create policy "Support staff can read staff directory" on public.support_staff for select to authenticated
using (private.support_is_staff());
create policy "Customers read own tickets and staff read all" on public.support_tickets for select to authenticated
using (user_id = (select private.support_firebase_uid()) or private.support_is_staff());
create policy "Customers create own tickets" on public.support_tickets for insert to authenticated
with check (user_id = (select private.support_firebase_uid()) and ((private.support_is_staff()) or (assigned_to is null and status='open' and priority='normal')));
create policy "Staff update tickets" on public.support_tickets for update to authenticated
using (private.support_is_staff()) with check (private.support_is_staff());
create policy "Ticket participants read messages" on public.support_messages for select to authenticated
using (
  exists (select 1 from public.support_tickets t where t.id=ticket_id and (t.user_id=(select private.support_firebase_uid()) or private.support_is_staff()))
  and (not is_internal or private.support_is_staff())
);
create policy "Ticket participants send public messages" on public.support_messages for insert to authenticated
with check (
  sender_id=(select private.support_firebase_uid()) and is_internal=false
  and exists (select 1 from public.support_tickets t where t.id=ticket_id and (t.user_id=(select private.support_firebase_uid()) or private.support_is_staff()))
);
create policy "Staff send internal notes" on public.support_messages for insert to authenticated
with check (sender_id=(select private.support_firebase_uid()) and is_internal=true and private.support_is_staff()
  and exists (select 1 from public.support_tickets t where t.id=ticket_id));

grant select on public.support_staff to authenticated;
grant select, insert on public.support_tickets to authenticated;
grant update (status, priority, assigned_to, updated_at) on public.support_tickets to authenticated;
grant select, insert on public.support_messages to authenticated;
grant usage, select on sequence public.support_tickets_ticket_number_seq to authenticated;

do $$ begin alter publication supabase_realtime add table public.support_tickets; exception when duplicate_object then null; end $$;
do $$ begin alter publication supabase_realtime add table public.support_messages; exception when duplicate_object then null; end $$;

